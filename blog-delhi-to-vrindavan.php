<h2>Braj: Close Enough for a Day Trip</h2>
<p>Vrindavan and Mathura, the land of Shri Krishna's childhood, are only about 165 km from Delhi on the Yamuna Expressway. That makes Braj one of the easiest yatras from Delhi NCR, as a single day trip or a relaxed weekend.</p>

<h3>The Route</h3>
<p>From Delhi, take the DND or Noida–Greater Noida Expressway to the Yamuna Expressway and exit at the Mathura/Vrindavan interchange. The drive is about 3 hours. Inside Vrindavan the lanes are narrow and crowded, so a driver who knows the parking spots near the temples saves a lot of time.</p>

<h3>Temples You Should Not Miss</h3>
<ul>
<li><strong>Shri Banke Bihari Temple:</strong> the most loved temple of Vrindavan. Darshan is in short sessions, and the crowd is heavy on weekends.</li>
<li><strong>Prem Mandir:</strong> a white marble temple that glows in changing colours after sunset.</li>
<li><strong>ISKCON Vrindavan:</strong> the Krishna Balaram Mandir, full of kirtan through the day.</li>
<li><strong>Nidhivan:</strong> the sacred grove of twisted trees, closed after the evening aarti.</li>
<li><strong>Shri Krishna Janmabhoomi, Mathura:</strong> the birthplace of Shri Krishna, about 12 km from Vrindavan.</li>
</ul>

<h3>Add Govardhan and Barsana</h3>
<p>With a second day, add <strong>Govardhan</strong> for darshan of Giriraj Ji and Mansi Ganga, and <strong>Barsana</strong> for the Shri Radha Rani Temple on the hill. The full Govardhan parikrama is about 21 km, so keep a separate morning for it.</p>

<h3>Best Time to Visit</h3>
<p>October to March is pleasant. Holi (especially the Lathmar Holi of Barsana) and Janmashtami are magical but extremely crowded: book your vehicle well in advance and start very early.</p>

