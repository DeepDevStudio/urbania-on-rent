<h2>The Golden City of the Thar</h2>
<p>Jaisalmer rises out of the Thar Desert in golden sandstone. Its fort is one of the few living forts in the world, with shops, homes and temples still inside its walls. A road trip from Delhi is long, but the desert landscape on the way is part of the experience.</p>

<h3>Route and Plan</h3>
<p>Jaisalmer is about 770 km from Delhi. Break the journey with a night in <strong>Bikaner</strong> (Junagarh Fort, Karni Mata Temple) or <strong>Jodhpur</strong> (Mehrangarh Fort). A good group plan is 5 to 6 days: Delhi – Bikaner – Jaisalmer (2 nights) – Jodhpur – Delhi.</p>

<h3>What to See in Jaisalmer</h3>
<ul>
<li><strong>Jaisalmer Fort (Sonar Quila):</strong> the golden fort with Jain temples and city views.</li>
<li><strong>Patwon ki Haveli:</strong> five finely carved merchant havelis in one lane.</li>
<li><strong>Gadisar Lake:</strong> an old water reservoir with ghats and chhatris, lovely at sunrise.</li>
<li><strong>Sam Sand Dunes:</strong> camel rides, folk music and a night in a desert camp.</li>
<li><strong>Kuldhara:</strong> the abandoned village on the way to the dunes.</li>
</ul>

<h3>Best Time to Visit</h3>
<p>October to March. Days are pleasant and desert nights are cold, so carry warm clothes for the camp. Summer (April to June) is very hot.</p>

