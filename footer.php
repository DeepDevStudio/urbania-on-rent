    <script>
        // Mobile Drawer Menu Toggle
        const hamburger = document.getElementById('hamburger');
        const navContainer = document.getElementById('navContainer');
        const navClose = document.getElementById('navClose');
        const navOverlay = document.getElementById('navOverlay');

        function openMobileMenu() {
            if (navContainer) navContainer.classList.add('active');
            if (navOverlay) navOverlay.classList.add('active');
            document.body.classList.add('nav-open');
            document.body.style.overflow = 'hidden';
        }

        function closeMobileMenu() {
            if (navContainer) navContainer.classList.remove('active');
            if (navOverlay) navOverlay.classList.remove('active');
            document.body.classList.remove('nav-open');
            document.body.style.overflow = '';
        }

        if (hamburger) hamburger.addEventListener('click', openMobileMenu);
        if (navClose) navClose.addEventListener('click', closeMobileMenu);
        if (navOverlay) navOverlay.addEventListener('click', closeMobileMenu);

        document.querySelectorAll('.nav-menu a').forEach(link => {
            link.addEventListener('click', closeMobileMenu);
        });

        // Back to Top Button
        const backToTopBtn = document.getElementById("backToTop");
        if (backToTopBtn) {
            window.addEventListener("scroll", () => {
                if (window.scrollY > 350) {
                    backToTopBtn.classList.add("show");
                } else {
                    backToTopBtn.classList.remove("show");
                }
            });

            backToTopBtn.addEventListener("click", () => {
                window.scrollTo({
                    top: 0,
                    behavior: "smooth"
                });
            });
        }

        // Intersection Observer for scroll animations
        const observerOptions = {
            threshold: 0.15,
            rootMargin: '0px 0px -40px 0px'
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('visible');
                    observer.unobserve(entry.target);
                }
            });
        }, observerOptions);

        document.querySelectorAll('.section-title, .hero-text, .hero-image, .about-content, .about-image, .feature-card, .fleet-card, .why-item, .testimonial-card, .blog-card, .pricing-card').forEach(el => {
            if (el) observer.observe(el);
        });
    </script>
