<h2>A Hill Station Without the Crowds</h2>
<p>Lansdowne is a small cantonment town in the Garhwal hills of Uttarakhand, home of the Garhwal Rifles. With pine and oak forests, clean roads and very little traffic, it is the perfect quiet weekend from Delhi for families and senior citizens.</p>

<h3>Route from Delhi</h3>
<p>Take the Delhi to Meerut Expressway to Meerut, then Bijnor and Najibabad to Kotdwar, and the hill road up to Lansdowne. The distance is about 260 km, around 6 hours. The last 40 km from Kotdwar are winding but well maintained.</p>

<h3>What to See</h3>
<ul>
<li><strong>Bhulla Tal:</strong> a small lake with boating, maintained by the army.</li>
<li><strong>Tip-n-Top (Tiffin Top):</strong> a viewpoint over the valleys and, on clear days, the Himalayan peaks.</li>
<li><strong>St. Mary's Church:</strong> an old church from the British era.</li>
<li><strong>Garhwal Rifles War Memorial and Museum:</strong> the history of the regiment.</li>
<li><strong>Tarkeshwar Mahadev Temple:</strong> a Shiva temple in deodar forest, about 35 km away.</li>
</ul>

<h3>Best Time to Visit</h3>
<p>March to June and October to February. The monsoon turns the hills deep green but brings fog and slippery roads. Winters are cold; carry warm clothes.</p>

