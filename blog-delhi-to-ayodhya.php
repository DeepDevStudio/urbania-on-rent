<h2>A Yatra Every Family Wants to Make</h2>
<p>Since the Shri Ram Janmabhoomi Mandir opened in January 2024, Ayodhya has become one of the most visited pilgrimages in India. From Delhi it is a long but smooth drive, with expressways for most of the way.</p>

<h3>Route from Delhi to Ayodhya</h3>
<p>Take the Yamuna Expressway to Agra and the Agra–Lucknow Expressway to Lucknow, then NH27 to Ayodhya. The distance is about 690 km, around 10 to 11 hours with breaks. Most groups plan 3 days: one day to reach, one full day of darshan, and one day to return.</p>

<h3>Places to Visit in Ayodhya</h3>
<ul>
<li><strong>Shri Ram Janmabhoomi Mandir:</strong> the grand new temple of Ram Lalla.</li>
<li><strong>Hanuman Garhi:</strong> the hill-top temple of Hanuman Ji, traditionally visited before Ram Lalla's darshan.</li>
<li><strong>Kanak Bhawan:</strong> the beautiful temple of Shri Sita-Ram.</li>
<li><strong>Saryu Ghats:</strong> evening aarti at Ram ki Paidi on the banks of the Saryu.</li>
</ul>

<h3>Darshan Tips</h3>
<ul>
<li>Mobile phones, bags and many other items are not allowed inside the Ram Mandir; use the lockers or leave them in the vehicle.</li>
<li>Go early in the morning on weekdays for a shorter queue.</li>
<li>Carry a valid photo ID for every member of the group.</li>
</ul>

