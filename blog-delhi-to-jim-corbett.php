<h2>India's Oldest National Park</h2>
<p>Jim Corbett National Park, set up in 1936, is India's oldest national park and home to tigers, wild elephants, deer and hundreds of bird species. Its resorts around Ramnagar make it a favourite weekend getaway for families, friends and corporate offsites from Delhi.</p>

<h3>Route from Delhi to Corbett</h3>
<p>The usual route is via NH9 to Moradabad and then Kashipur to Ramnagar, about 255 km and 5 to 6 hours. Starting early helps you reach the resort by lunch and catch an evening safari.</p>

<h3>Safari Zones and Permits</h3>
<ul>
<li><strong>Dhikala:</strong> the best-known zone, with wide grasslands; open only in the season, roughly mid-November to mid-June.</li>
<li><strong>Bijrani, Durga Devi and Garjia:</strong> other popular zones for jeep safaris.</li>
<li><strong>Jhirna and Dhela:</strong> open for most of the year, including the monsoon.</li>
</ul>
<p>Safari permits are booked online in advance and sell out on weekends, so book as soon as your dates are fixed. Carry the ID used for the booking.</p>

<h3>Other Things to Do</h3>
<ul>
<li><strong>Garjia Devi Temple:</strong> a temple of the goddess on a rock in the Kosi river.</li>
<li><strong>Corbett Falls:</strong> a short drive from Ramnagar.</li>
<li>Riverside walks, bird watching and evening bonfires at the resort.</li>
</ul>

